@dataclass
class _Analyzed:
    fixture: Fixture
    prediction: MatchPrediction
    dataset: MatchRawDataset


@dataclass
class _Pool:
    analyzed: list[_Analyzed]
    total_fixtures: int          # o gün gelecekteki toplam maç
    selected: int                # analiz için seçilen aday sayısı
    failed: int = 0
    truncated: bool = False      # zaman bütçesi dolduğu için yarım kaldı mı
    errors: Counter = field(default_factory=Counter)


class DailyPicksService:
    def __init__(self, analysis_service: AnalysisService):
        self._service = analysis_service

    async def _future_fixtures(self, target: date) -> tuple[list[Fixture], int]:
        provider = self._service._provider
        try:
            # Yalnızca başlamamış maçlar: biten maçlar da çekilince liste ~2 kat sayfa tutuyordu.
            fixtures = await provider.get_fixtures(target, status="scheduled")
        except TypeError:
            fixtures = await provider.get_fixtures(target)
        upcoming = select_upcoming(fixtures, target_date=target)
        total = len(upcoming)

        # Piyasası (1X2) açık görünen maçlar: İdeal/Sürpriz/İY-MS hepsi piyasa
        # gerektirir; piyasası olmayan maça analiz çağrısı harcamanın anlamı yok.
        open_ids = getattr(self._service._provider, "open_odds_match_ids", None)
        if open_ids:
            with_market = [f for f in upcoming if f.match_id in open_ids]
            if with_market:
                upcoming = with_market

        # Aday seçimi: İlk Yarı 1X2 piyasası açık maçlar (iddaa'da İY/MS'nin açık olduğu
        # majör ligler) ÖNCELİKLİ. Kalan kontenjan, günün en kalabalık liglerinden doldurulur.
        # Her aşamada ligler arasında dönüşümlü (round-robin) seçilir ki adaylar tek lige
        # yığılmasın. Sıralama deterministiktir.
        # Majör ligler (bahis sitelerinde İY/MS ve tüm piyasaların açık olduğu ligler) her zaman
        # öncelikli: önce majör liglerin maçları ligler arasında dönüşümlü seçilir, kalan kontenjan
        # ilk yarı piyasası açık, sonra diğer maçlarla doldurulur.
        open_ht = getattr(self._service._provider, "open_ht_match_ids", None) or set()
        major = [f for f in upcoming if is_major_league(f.league_name)]
        others = [f for f in upcoming if not is_major_league(f.league_name)]
        ht_others = [f for f in others if f.match_id in open_ht]
        rest = [f for f in others if f.match_id not in open_ht]

        picked = self._round_robin(major, MAX_HT_LEAGUES, MAX_CANDIDATES)
        for group, cap in ((ht_others, MAX_LEAGUES), (rest, MAX_LEAGUES)):
            if len(picked) < MAX_CANDIDATES:
                picked += self._round_robin(group, cap, MAX_CANDIDATES - len(picked))
        return picked, total

    @staticmethod
    def _round_robin(fixtures: list[Fixture], max_leagues: int, limit: int) -> list[Fixture]:
        if not fixtures or limit <= 0:
            return []
        per_league = Counter(f.league_id for f in fixtures)
        leagues = [lid for lid, _ in sorted(per_league.items(), key=lambda kv: (-kv[1], kv[0]))[:max_leagues]]
        queues = {
            lid: sorted((f for f in fixtures if f.league_id == lid), key=lambda f: (f.kickoff, f.match_id))
            for lid in leagues
        }
        picked: list[Fixture] = []
        while len(picked) < limit and any(queues.values()):
            for lid in leagues:
                if queues[lid] and len(picked) < limit:
                    picked.append(queues[lid].pop(0))
        return picked

    async def _analyze_all(self, fixtures: list[Fixture], pool: _Pool) -> None:
        """Maçları sırayla analiz eder ve sonuçları paylaşılan `pool`a EKLER; böylece
        istek süresi dolsa bile arka plan analizi sürer ve ilerleme görülebilir."""
        for fixture in fixtures:
            try:
                prediction = await self._service.analyze_match(fixture.match_id, include_evidence=False)
                dataset = await self._service.get_dataset(fixture.match_id)
            except BayTahminError as exc:
                pool.failed += 1
                pool.errors[type(exc).__name__] += 1
                logger.warning("daily_picks: %s analiz edilemedi: %s: %s", fixture.match_id, type(exc).__name__, exc)
                continue
            pool.analyzed.append(_Analyzed(fixture=fixture, prediction=prediction, dataset=dataset))
        logger.info(
            "daily_picks: toplam=%d seçilen=%d analiz_edilen=%d başarısız=%d hatalar=%s",
            pool.total_fixtures, pool.selected, len(pool.analyzed), pool.failed, dict(pool.errors),
        )

    async def _build_pool(self, key: str, target: date) -> None:
        pool = _Pool(analyzed=[], total_fixtures=0, selected=0, truncated=True)
        _pool_live[key] = pool
        try:
            fixtures, total = await self._future_fixtures(target)
            pool.total_fixtures, pool.selected = total, len(fixtures)
            await self._analyze_all(fixtures, pool)
        except BayTahminError as exc:
            pool.failed += 1
            pool.errors[type(exc).__name__] += 1
            logger.warning("daily_picks: gün listesi alınamadı: %s", exc)
        finally:
            pool.truncated = False
            ttl = _PARTIAL_POOL_TTL_SECONDS if (pool.failed and not pool.analyzed) else _PICKS_CACHE_TTL_SECONDS
            _analysis_pool_cache.set(key, pool, ttl)
            _pool_live.pop(key, None)
            _pool_tasks.pop(key, None)
        if pool.analyzed:
            await self._save_snapshots(target, pool)
            # 2. aşama: günlük liste yalnızca 1X2 taşır; Alt/Üst, KG ve handikap oranlarını (Sürpriz kartı ve
            # İdeal'in Üst/KG seçimleri için gerekli) başlama saati yakın olandan başlayarak ekler.
            try:
                await self._enrich_pool(target, pool)
            except Exception as exc:  # noqa: BLE001
                logger.warning("daily_picks: oran zenginleştirme hatası: %s", exc)

    async def _enrich_pool(self, target: date, pool: "_Pool") -> None:
        items = sorted(pool.analyzed, key=lambda i: i.fixture.kickoff)
        done = 0
        for item in items:
            if await self._service.enrich_odds(item.dataset):
                done += 1
                if done % 12 == 0:
                    await self._save_snapshots(target, pool)
        if done:
            logger.info("daily_picks: %d maç için tam oran eklendi", done)
            await self._save_snapshots(target, pool)

    async def _get_pool(self, target: date, wait: float | None = REQUEST_WAIT_SECONDS) -> _Pool:
        key = target.isoformat()
        cached = _analysis_pool_cache.get(key)
        if cached is not None:
            return cached
        task = _pool_tasks.get(key)
        if task is None:
            # Analiz ARKA PLANDA sürer (istek iptal olsa da); istek yalnızca
            # `wait` saniye bekler ve o ana kadarki sonuçla yanıt verir.
            task = asyncio.create_task(self._build_pool(key, target))
            _pool_tasks[key] = task
        try:
            await asyncio.wait_for(asyncio.shield(task), wait)
        except asyncio.TimeoutError:
            live = _pool_live.get(key)
            if live is not None:
                return live
        return _analysis_pool_cache.get(key) or _pool_live.get(key) or _Pool(analyzed=[], total_fixtures=0, selected=0, truncated=True)

    # ------------------------------------------------------------ snapshots
    def _assemble(self, category: str, target: date, limit: int, pool: _Pool) -> DailyPicksResponse:
        """Havuzdan (saf, I/O'suz) bir kategorinin yanıtını üretir; kategoriler arası dışlama dahil."""
        analyzed = pool.analyzed
        ideal_picks = self._build_ideal(analyzed, limit)
        used = {p.match_id for p in ideal_picks}
        if category == "ideal":
            picks = ideal_picks
        else:
            surprise_picks = self._build_surprise(analyzed, limit, exclude=used)
            if category == "surprise":
                picks = surprise_picks
            else:
                used |= {p.match_id for p in surprise_picks}
                picks = self._build_iyms_surprise(analyzed, limit, exclude=used)

        note = None
        if not picks and not pool.truncated and category == "iyms_surprise" and analyzed:
            majors = sum(1 for i in analyzed if is_major_league(i.fixture.league_name))
            note = (
                f"{target.isoformat()} için analiz edilen {len(analyzed)} maçın {majors} tanesi majör ligden; "
                "İY/MS yalnızca majör liglerde önerildiği için bu kriteri sağlayan gerçek bir maç bulunamadı. "
                "Uydurma tahmin üretilmedi."
            )
        elif not picks and not pool.truncated:
            note = self._empty_note(target, pool)
        elif len(picks) < limit and not pool.truncated:
            note = (
                f"Bu kriterleri karşılayan (İY/MS için majör ligler) ve diğer kartlarda kullanılmamış yalnızca {len(picks)} gerçek maç bulundu "
                f"({len(analyzed)} maç analiz edildi)."
            )
        if pool.truncated:
            progress = f"{len(analyzed)}/{pool.selected or '?'} maç analiz edildi"
            note = (
                f"Analiz arka planda sürüyor ({progress}); sağlayıcının hız sınırı nedeniyle birkaç dakika "
                "sürebilir. Sonuçlar hazır oldukça bu sayfada güncellenecek."
                + (" Şu ana kadarki sonuç gösteriliyor." if picks else "")
            )
        if category == "iyms_surprise" and picks:
            warn = (
                "Düşük isabet uyarısı: İY/MS tahminleri ölçülen geçmiş sonuçlarda düşük tutturma oranına "
                "sahip (yaklaşık 9/51). Bu kart yüksek riskli, eğlence amaçlı bir seçkidir; ciddi kupon için önerilmez."
            )
            note = f"{warn} {note}" if note else warn
        return DailyPicksResponse(
            generated_at=datetime.now(timezone.utc), target_date=target, category=category,
            picks=picks, candidates_considered=len(analyzed),
            disclaimer=_DISCLAIMERS[category], note=note,
        )

    async def _save_snapshots(self, target: date, pool: _Pool) -> None:
        """Her kategori × adet için hazır yanıtı Supabase'e yazar (best-effort, asla hata fırlatmaz)."""
        try:
            now = datetime.now(timezone.utc).isoformat()
            rows = []
            for category in _CATEGORIES:
                for limit in SNAPSHOT_LIMITS:
                    resp = self._assemble(category, target, limit, pool)
                    rows.append({
                        "target_date": target.isoformat(), "category": f"{category}:{limit}",
                        "payload": resp.model_dump(mode="json"), "updated_at": now,
                    })
            await accuracy._db(
                "POST", "daily_picks_snapshot", params={"on_conflict": "target_date,category"},
                json_body=rows, prefer=True,
            )
            logger.info("daily_picks: %s için %d snapshot kaydedildi (%d maç analiz edildi)",
                        target.isoformat(), len(rows), len(pool.analyzed))
        except Exception as exc:
            logger.warning("daily_picks: snapshot kaydedilemedi: %s", exc)

    async def _load_snapshot(self, category: str, target: date, limit: int):
        """(response, yaş_saniye) veya None. Başlamış maçlar ayıklanır."""
        try:
            rows = await accuracy._db(
                "GET", "daily_picks_snapshot",
                params={
                    "target_date": f"eq.{target.isoformat()}",
                    "category": f"in.({category}:{limit},{category}:{SNAPSHOT_LIMITS[-1]})",
                    "select": "category,payload,updated_at",
                },
            )
        except Exception as exc:
            logger.warning("daily_picks: snapshot okunamadı: %s", exc)
            return None
        by_cat = {
            r["category"]: r for r in rows or []
            if datetime.fromisoformat(str(r["updated_at"]).replace("Z", "+00:00")) >= SNAPSHOT_MIN_UPDATED
        }
        now = datetime.now(timezone.utc)

        def parse(row):
            resp = DailyPicksResponse.model_validate(row["payload"])
            updated = datetime.fromisoformat(str(row["updated_at"]).replace("Z", "+00:00"))
            return resp, (now - updated).total_seconds()

        exact = by_cat.get(f"{category}:{limit}")
        if exact:
            resp, age = parse(exact)
            if all(p.kickoff > now for p in resp.picks):
                return resp, age
        # Bazı maçlar başladı (ya da satır yok): en büyük snapshot'tan başlamamış ilk `limit` seçim.
        big = by_cat.get(f"{category}:{SNAPSHOT_LIMITS[-1]}")
        if big:
            resp, age = parse(big)
            fresh = [p for p in resp.picks if p.kickoff > now][:limit]
            if fresh:
                resp.picks = fresh
                resp.note = None if len(fresh) >= limit else resp.note
                return resp, age
        return None

    async def _refresh_in_background(self, target: date) -> None:
        key = target.isoformat()
        last = _refresh_started.get(key, 0.0)
        if key in _pool_tasks or (asyncio.get_event_loop().time() - last) < 600:
            return
        _refresh_started[key] = asyncio.get_event_loop().time()
        try:
            await self._get_pool(target, wait=None)
        except Exception as exc:
            logger.warning("daily_picks: arka plan yenileme başarısız: %s", exc)

    async def precompute_loop(self) -> None:
        """Sunucu ayaktayken bugünü ve yarını önceden hesaplar; kullanıcı beklemez."""
        from app.core import api_gate
        api_gate.background.set(False)
        api_gate.picks.set(True)  # kartlar: kullanıcı tıklamasından sonra, arka plandan önce
        await asyncio.sleep(3)
        while True:
            for offset in (0, 1):
                target = istanbul_today() + timedelta(days=offset)
                try:
                    pool_key = target.isoformat()
                    snap = await self._load_snapshot("ideal", target, SNAPSHOT_LIMITS[-1])
                    if snap is None or snap[1] > SNAPSHOT_REFRESH_SECONDS:
                        _analysis_pool_cache.invalidate(pool_key)
                        await self._get_pool(target, wait=None)
                except Exception as exc:
                    logger.warning("daily_picks: önhesaplama hatası (%s): %s", target, exc)
            await asyncio.sleep(PRECOMPUTE_INTERVAL_SECONDS)

    async def build(self, category: str, target: date, limit: int = 4) -> DailyPicksResponse:
        if category not in _DISCLAIMERS:
            raise ValueError(f"Unknown picks category: {category!r}")

        cache_key = f"{category}:{target.isoformat()}:{limit}"
        cached = _picks_response_cache.get(cache_key)
        if cached is not None:
            return cached

        # 1) Hazır snapshot varsa ANINDA döner (bayatsa arka planda yenilenir).
        if limit in SNAPSHOT_LIMITS:
            snap = await self._load_snapshot(category, target, limit)
            if snap is not None:
                result, age = snap
                if age > SNAPSHOT_REFRESH_SECONDS:
                    asyncio.create_task(self._refresh_in_background(target))
                _picks_response_cache.set(cache_key, result, 60)
                await self._record_for_accuracy(result.picks, category)
                return result

        # 2) Snapshot yok: ortak havuzdan hesapla (kısa süre bekler, kalanı arka planda sürer).
        pool = await self._get_pool(target)
        result = self._assemble(category, target, limit, pool)
        await self._record_for_accuracy(result.picks, category)
        analyzed = pool.analyzed
        ttl = 8 if pool.truncated else (_PARTIAL_POOL_TTL_SECONDS if (pool.failed and not analyzed) else _PICKS_CACHE_TTL_SECONDS)
        _picks_response_cache.set(cache_key, result, ttl)
        return result

    @staticmethod
    def _empty_note(target: date, pool: _Pool) -> str:
        day = target.isoformat()
        if pool.total_fixtures == 0:
            return f"{day} için gelecekte başlayacak maç bulunamadı."
        if pool.failed and not pool.analyzed:
            return (
                f"{day} için {pool.total_fixtures} maç var, ancak veri sağlayıcıdan istatistik çekilemediği için "
                f"hiçbiri analiz edilemedi (geçici hız sınırı olabilir). Birkaç dakika sonra tekrar deneyin."
            )
        if pool.truncated and not pool.analyzed:
            return f"{day} için analiz henüz tamamlanmadı; birkaç dakika sonra tekrar deneyin."
        return (
            f"{day} için {pool.total_fixtures} maçtan {len(pool.analyzed)} tanesi analiz edildi "
            f"({pool.failed} tanesinde veri yetersiz/alınamadı); bu kategorinin istatistiksel kriterlerini "
            "karşılayan (ve diğer kartlarda kullanılmayan) maç yok. Uydurma tahmin üretilmedi."
        )

    @staticmethod
    async def _record_for_accuracy(picks: list[PickCandidate], category: str = "") -> None:
        """Best-effort: every real pick shown to a user is logged for the
        admin panel's won/lost accuracy tracking. Never raises -- a tracking
        failure (Supabase down, not configured, etc.) must never break the
        picks response itself."""
        for pick in picks:
            market_type = _ACCURACY_MARKET_CODES.get(pick.market)
            if market_type is None:
                continue
            try:
                await accuracy.save_prediction({
                    "match_id": pick.match_id, "kickoff": pick.kickoff.isoformat(),
                    "competition": pick.league_name, "home_team": pick.home_team, "away_team": pick.away_team,
                    "market_type": market_type, "selection": pick.selection,
                    "market_probability": pick.confidence, "odd": pick.odd, "card": category,
                })
            except Exception:
                pass

    @staticmethod
    def _build_ideal(analyzed: list[_Analyzed], limit: int) -> list[PickCandidate]:
        scored: list[PickCandidate] = []
        for item in analyzed:
            candidate = mme.ideal_candidate_for_match(item.prediction, item.dataset)
            if candidate is not None:
                scored.append(candidate)
        scored.sort(key=lambda c: (c.model_probability, c.confidence), reverse=True)
        return scored[:limit]

    @staticmethod
    def _build_surprise(analyzed: list[_Analyzed], limit: int, exclude: set[str] | None = None) -> list[PickCandidate]:
        exclude = exclude or set()
        pool: list[PickCandidate] = []
        for item in analyzed:
            if item.fixture.match_id in exclude:
                continue
            pool.extend(mme.surprise_candidates_for_match(item.prediction, item.dataset))
        pool.sort(key=lambda c: c.divergence or 0.0, reverse=True)

        chosen: list[PickCandidate] = []
        seen_matches: set[str] = set()
        for candidate in pool:
            if candidate.match_id in seen_matches:
                continue
            chosen.append(candidate)
            seen_matches.add(candidate.match_id)
            if len(chosen) >= limit:
                break
        return chosen

    @staticmethod
    def _has_ht_market(item: _Analyzed) -> bool:
        return any("ilk yarı maç sonucu" in (m.market_name or "").lower().replace("i̇", "i")
                   for m in item.dataset.odds_markets)

    @staticmethod
    def _build_iyms_surprise(analyzed: list[_Analyzed], limit: int, exclude: set[str] | None = None) -> list[PickCandidate]:
        exclude = exclude or set()
        # İY/MS yalnızca MAJÖR liglerden önerilir (bahis sitelerinde İY/MS'nin açık olduğu ligler);
        # alt lig / bilinmeyen lig maçları ilk yarı piyasası görünse bile önerilmez.
        eligible = [i for i in analyzed if is_major_league(i.fixture.league_name)]

        pool = [
            (surprise.confidence, item, surprise)
            for item in eligible
            if item.fixture.match_id not in exclude
            for surprise in item.prediction.surprises
        ]
        pool.sort(key=lambda row: row[0], reverse=True)

        def joint_probability(item: _Analyzed, combo: str) -> float:
            return float(item.prediction.half_time_full_time.matrix.get(combo, 0.0))

        def to_pick(item: _Analyzed, surprise) -> PickCandidate:
            fixture, prediction = item.fixture, item.prediction
            return PickCandidate(
                match_id=fixture.match_id, home_team=prediction.home_team.team_name,
                away_team=prediction.away_team.team_name, league_name=fixture.league_name,
                kickoff=fixture.kickoff, market="İlk Yarı/Maç Sonucu (İY/MS)", selection=surprise.combination,
                # GERÇEK model olasılığı (bileşik İY/MS hücresi); "plausibility" ölçekli bir skordur.
                model_probability=joint_probability(item, surprise.combination),
                market_probability=None, divergence=None,
                confidence=surprise.confidence, risk=surprise.risk, data_quality=prediction.data_quality,
                rationale=f"{surprise.description} {prediction.analysis_rationale or ''}".strip(),
            )

        chosen: list[PickCandidate] = []
        seen_matches: set[str] = set()
        seen_combos: set[str] = set()

        # Pass 0: "dönüş" kombinasyonları (1/2 ve 2/1) olasılıkları küçük olduğu için
        # skor sıralamasında hep sona düşüyordu ve hiç önerilmiyordu. Her biri için, modelin
        # en yüksek GERÇEK olasılık verdiği maç (eşik üstündeyse) bir slot alır.
        if limit >= 3:
            for combo in ("2/1", "1/2"):
                best = None
                for _score, item, surprise in pool:
                    if surprise.combination != combo or item.fixture.match_id in seen_matches:
                        continue
                    prob = joint_probability(item, combo)
                    if prob >= IYMS_MIN_SWING_PROBABILITY and (best is None or prob > best[0]):
                        best = (prob, item, surprise)
                if best is not None:
                    chosen.append(to_pick(best[1], best[2]))
                    seen_matches.add(best[1].fixture.match_id)
                    seen_combos.add(combo)

        # Pass 1: prefer both a new match AND a new İY/MS combination, so
        # the picks are genuinely varied rather than "X/1 four times over".
        for _score, item, surprise in pool:
            if len(chosen) >= limit:
                break
            if item.fixture.match_id in seen_matches or surprise.combination in seen_combos:
                continue
            chosen.append(to_pick(item, surprise))
            seen_matches.add(item.fixture.match_id)
            seen_combos.add(surprise.combination)

        # Pass 2: still one pick per match, but combos may repeat if there
        # weren't enough distinct combinations across distinct matches.
        if len(chosen) < limit:
            for _score, item, surprise in pool:
                if len(chosen) >= limit:
                    break
                if item.fixture.match_id in seen_matches:
                    continue
                chosen.append(to_pick(item, surprise))
                seen_matches.add(item.fixture.match_id)

        return chosen[:limit]
