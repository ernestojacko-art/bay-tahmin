# Analyzing one fixture means ~5+ outbound calls to the data provider
# (fixture detail, home team league history, away team league history, H2H,
# odds) -- and each of those can itself page through the provider's full
# league fixture list. 5DollarFootballAPI is a budget plan with a daily
# request credit cap, and a cold start (Render free-tier spin-down) wipes
# every in-memory cache, so a worst case of MAX_CANDIDATES fixtures x 3
# categories after a cold start can burn through a day's credit in minutes
# (confirmed in production 2026-10-06/07: "günlük kredi limitine takıldık").
# Keep this modest -- a real day rarely has more real, odds-open fixtures
# than this anyway. Configurable via env var so it can be tuned without a
# code change once real production credit usage is observed (2026-10-14:
# raised from the original 15 -> 30 as a moderate, "sen seç" default after
# the plan was confirmed as 5DollarFootballAPI "Pro"; watch Render logs for
# credit-limit errors and lower this again if they reappear).
MAX_LEAGUES = int(os.getenv("DAILY_PICKS_MAX_LEAGUES", "25"))
MAX_CANDIDATES = int(os.getenv("DAILY_PICKS_MAX_CANDIDATES", "150"))
# İlk Yarı 1X2 piyasası açık (iddaa'da İY/MS'nin açık olduğu majör) maçlar için lig sınırı:
# bu maçlar günde ligi başına 1-2 tane olduğundan daha çok lige yayılmak gerekir.
MAX_HT_LEAGUES = int(os.getenv("DAILY_PICKS_MAX_HT_LEAGUES", "30"))
# İY/MS kartında "dönüş" kombinasyonları (1/2, 2/1) için en az model olasılığı.
IYMS_MIN_SWING_PROBABILITY = float(os.getenv("IYMS_MIN_SWING_PROBABILITY", "0.02"))

# ---- Kalıcı snapshot (Supabase) -------------------------------------------------
# Kartlar kullanıcı beklerken hesaplanmaz: günlük havuz arka planda hazırlanır ve her kategori /
# her adet için hazır sonuç Supabase'e yazılır. İstek bu snapshot'ı ANINDA okur (yeniden
# deploy / uyku sonrası da kaybolmaz); bayatlamışsa eski sonuç gösterilirken arka planda yenilenir.
SNAPSHOT_LIMITS = tuple(range(1, 13))
# Bu andan ÖNCE yazılmış snapshot'lar eski seçim kurallarıyla üretildi (ör. düşük oranlı çifte şans); yok sayılır.
SNAPSHOT_MIN_UPDATED = datetime(2026, 10, 26, 8, 10, tzinfo=timezone.utc)
SNAPSHOT_REFRESH_SECONDS = int(os.getenv("DAILY_PICKS_SNAPSHOT_REFRESH_MINUTES", "90")) * 60
PRECOMPUTE_INTERVAL_SECONDS = int(os.getenv("DAILY_PICKS_PRECOMPUTE_MINUTES", "20")) * 60
_CATEGORIES = ("ideal", "surprise", "iyms_surprise")
_refresh_started: dict[str, float] = {}

# Response-level cache: once a category has been built for a given date,
# reuse it for a while instead of re-running the full analysis pipeline on
# every page load/poll. This is on top of (not a replacement for) the
# per-match caches in AnalysisService -- it's what actually stops repeated
# visits to the same day from re-fanning-out into dozens of fresh provider
# calls each time.
_PICKS_CACHE_TTL_SECONDS = 15 * 60
_picks_response_cache = TTLCache(default_ttl_seconds=_PICKS_CACHE_TTL_SECONDS)

# Üç kart (İdeal / Sürpriz / İY-MS) AYNI günün analizini paylaşır: analiz bir kez
# yapılır (tarih başına kilit), üç kategori de aynı havuzdan seçim yapar. Hem
# sağlayıcı çağrıları üçe katlanmaz hem de kategoriler arası "aynı maç üç
# kartta da çıkmasın" kuralı tutarlı uygulanabilir.
_analysis_pool_cache = TTLCache(default_ttl_seconds=_PICKS_CACHE_TTL_SECONDS)
_PARTIAL_POOL_TTL_SECONDS = 60
_pool_tasks: dict[str, "asyncio.Task"] = {}
_pool_live: dict[str, "_Pool"] = {}
# İstek en fazla bu kadar bekler; analiz bitmediyse o ana kadarki sonuçlar +
# "hazırlanıyor" notu döner, analiz arka planda biter ve sonraki çağrı anında yanıtlanır.
REQUEST_WAIT_SECONDS = float(os.getenv("DAILY_PICKS_REQUEST_WAIT_SECONDS", "40"))
# Tek bir istek en fazla bu kadar saniye analiz yapar; süre dolarsa o ana kadar
# analiz edilenlerle yanıt verilir, kalan maçlar bir sonraki çağrıda (önbellekten
# hızlıca) devam eder.

